import streamlit as st
import pandas as pd
import plotly.express as px


# ─────────────────────────────────────────────
# 페이지 설정
# ─────────────────────────────────────────────
st.set_page_config(
    page_title="영화 데이터 그래프 도감 1 - 시간",
    layout="wide",
)

st.title("영화 데이터 그래프 도감 1 - 시간")


# ─────────────────────────────────────────────
# 데이터 불러오기
# ─────────────────────────────────────────────
DATA_URL = "https://raw.githubusercontent.com/happykth/data/main/kobis_daily.csv"


@st.cache_data
def load_data():
    # 1년치(365일) 일별 박스오피스 10위권 기록
    df = pd.read_csv(DATA_URL)

    # 날짜 열을 진짜 날짜(datetime)로 변환
    df["날짜"] = pd.to_datetime(df["날짜"], format="%Y%m%d")

    return df


df = load_data()


# ─────────────────────────────────────────────
# 그래프 1. 한 영화의 흥행 곡선
# ─────────────────────────────────────────────
st.header("1. 한 영화의 흥행 곡선")

movie_list = sorted(df["영화명"].dropna().unique())

movie = st.selectbox(
    "영화를 고르세요",
    movie_list,
)

one_movie = (
    df[df["영화명"] == movie]
    .sort_values("날짜")
)

fig1 = px.line(
    one_movie,
    x="날짜",
    y="일관객",
    markers=True,
    labels={
        "날짜": "날짜",
        "일관객": "일관객",
    },
)

# 마우스를 올렸을 때 날짜와 관객 수 표시
fig1.update_traces(
    hovertemplate=(
        "날짜 %{x|%Y-%m-%d}"
        "<br>관객 %{y:,}명"
        "<extra></extra>"
    )
)

fig1.update_layout(
    hovermode="x unified",
)

st.plotly_chart(
    fig1,
    width="stretch",
)

st.caption("이 그래프로 알 수 있는 것: __________________________________")


